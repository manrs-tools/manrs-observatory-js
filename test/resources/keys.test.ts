import { describe, expect, it } from "vitest";
import { Client } from "../../src/client";
import { createMockFetch } from "../test-utils";

describe("ApiKeysResource", () => {
  it("supports the full create/get/find/update/delete lifecycle", async () => {
    const created = { id: "key-1", description: "test key", expiry: "2030-01-01T00:00:00Z" };
    const { fetch, calls } = createMockFetch([
      { body: { key: created } },
      { body: { key: created } },
      { body: { keys: [created] } },
      { body: { key: { ...created, description: "renamed" } } },
      { status: 204, bodyText: "" },
    ]);
    const client = new Client({ fetch });

    const key = await client.keys.create({ description: "test key", expiry: "2030-01-01T00:00:00Z" });
    expect(key).toEqual(created);

    const fetched = await client.keys.get("key-1");
    expect(fetched).toEqual(created);

    const found = await client.keys.find({ userID: "user-1" });
    expect(found).toEqual([created]);
    expect(calls[2]!.url).toContain("userID=user-1");

    const updated = await client.keys.update("key-1", { description: "renamed" });
    expect(updated.description).toBe("renamed");

    await client.keys.delete("key-1");
    expect(calls[4]!.method).toBe("DELETE");
    expect(calls[4]!.url).toBe("https://observatory.manrs.org/api/v2/keys/key-1");
  });

  it("create() does not send read-only fields from a fetched key", async () => {
    const fetched = {
      id: "key-1",
      created: "2026-09-02T13:34:30Z",
      autoGenerated: false,
      description: "probe",
      expiry: "2030-01-01T00:00:00Z",
      userID: "user-1",
    };
    const { fetch, calls } = createMockFetch([{ body: { key: { ...fetched, id: "key-2" } } }]);
    const client = new Client({ fetch });

    await client.keys.create({ ...fetched, description: "probe (clone)" });

    expect(JSON.parse(calls[0]!.body!)).toEqual({ key: { description: "probe (clone)", expiry: "2030-01-01T00:00:00Z" } });
  });

  it("create() throws when the `key` envelope is missing", async () => {
    const { fetch } = createMockFetch([{ body: {} }]);
    const client = new Client({ fetch });

    await expect(
      client.keys.create({ description: "test key", expiry: "2030-01-01T00:00:00Z" }),
    ).rejects.toMatchObject({
      name: "ManrsError",
      statusCode: 200,
      message: 'create response missing "key"',
    });
  });

  it("get() throws when the `key` envelope is missing", async () => {
    const { fetch } = createMockFetch([{ body: {} }]);
    const client = new Client({ fetch });

    await expect(client.keys.get("key-1")).rejects.toMatchObject({
      name: "ManrsError",
      statusCode: 200,
      message: 'API key key-1 response missing "key"',
    });
  });

  it("update() throws when the `key` envelope is missing", async () => {
    const { fetch } = createMockFetch([{ body: {} }]);
    const client = new Client({ fetch });

    await expect(client.keys.update("key-1", { description: "renamed" })).rejects.toMatchObject({
      name: "ManrsError",
      statusCode: 200,
      message: 'API key key-1 update response missing "key"',
    });
  });

  it("delete() encodes special characters in the key ID", async () => {
    const { fetch, calls } = createMockFetch([{ status: 204, bodyText: "" }]);
    const client = new Client({ fetch });

    await client.keys.delete("key/with?special#chars");

    expect(calls[0]!.url).toBe("https://observatory.manrs.org/api/v2/keys/key%2Fwith%3Fspecial%23chars");
  });
});
