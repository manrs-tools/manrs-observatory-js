import { describe, expect, it } from "vitest";
import { APIKeyReadOnlyFields, TicketReplyReadOnlyFields, type APIKey, type TicketReply } from "../models";
import { writable } from "../src/body";

describe("writable", () => {
  it("drops read-only fields and keeps everything else", () => {
    const fetched: APIKey = {
      id: "39d9b4e08b84b1d2bb191f33",
      created: "2026-09-02T13:34:30Z",
      autoGenerated: false,
      description: "probe",
      expiry: "2027-01-01T00:00:00Z",
      key: "ba7378fb-034b-40b1-b37f-edb8476bf8e7",
      userID: "019ed253-ddb2-75a4-8f86-39d9b4e08b84",
    };

    expect(writable(fetched, APIKeyReadOnlyFields)).toEqual({ description: "probe", expiry: "2027-01-01T00:00:00Z" });
    expect(fetched.id).toBe("39d9b4e08b84b1d2bb191f33");
  });

  it("marks the fields the API contract marks, not every identifier-looking field", () => {
    expect([...APIKeyReadOnlyFields].sort()).toEqual(["autoGenerated", "created", "id", "key", "userID"]);
    expect(TicketReplyReadOnlyFields.has("id")).toBe(true);
    expect(TicketReplyReadOnlyFields.has("ticketID")).toBe(false);

    const reply: TicketReply = { ticketID: "t-001", message: "hi", id: "r-001", staff: true };
    expect(writable(reply, TicketReplyReadOnlyFields)).toEqual({ ticketID: "t-001", message: "hi" });
  });
});
